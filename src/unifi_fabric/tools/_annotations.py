"""MCP tool annotations: which tools read, which write, which can destroy.

Every ``@mcp.tool`` passes ``annotations=TOOL_CLASS["<tool name>"]`` so MCP clients and
gateways can tell reads from writes (e.g. auto-approve reads, confirm destructive calls).
This is metadata only: it changes no tool behaviour, arguments or responses, and does not
replace the server-side write gates (``confirm=true`` and the ``UNIFI_ENABLE_*`` flags).

The classification is explicit, one tool name per entry, never derived from a name prefix
at runtime. A tool registered without an entry fails at import time with ``KeyError``, and
``tests/test_annotations.py`` checks this mapping against the registered tools both ways.

Classes (``openWorldHint`` is deliberately left unset):

- ``READ_ONLY``: reads only. Some reads are POST queries (``query_isp_metrics``,
  ``list_client_sessions``, ``get_historical_stats``) that change nothing.
- ``ADDITIVE``: writes that add or start something without removing or overwriting
  existing state (create, adopt, assign, attach, PTZ moves, unblock, ...).
- ``DESTRUCTIVE``: writes that delete, overwrite, interrupt or trigger something
  (delete, patch, restart, upgrade, block, suspend, sirens, alarm outputs, ...).
- ``DESTRUCTIVE_IDEMPOTENT``: destructive writes that converge on the requested state, so
  repeating the same call has no additional effect (``update_*``, ``set_*``).
"""

