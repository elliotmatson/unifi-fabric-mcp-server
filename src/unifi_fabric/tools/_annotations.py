def _build() -> dict[str, ToolAnnotations]:
    table: dict[str, ToolAnnotations] = {}
    for names, hints in (
        (_READ_ONLY_TOOLS, READ_ONLY),
        (_ADDITIVE_TOOLS, ADDITIVE),
        (_DESTRUCTIVE_TOOLS, DESTRUCTIVE),
        (_DESTRUCTIVE_IDEMPOTENT_TOOLS, DESTRUCTIVE_IDEMPOTENT),
    ):
        for name in names:
            if name in table:
                raise ValueError(f"tool {name!r} is listed in more than one class")
            table[name] = hints
    return table


TOOL_CLASS: dict[str, ToolAnnotations] = _build()
"""Tool name -> its annotations. The single source of truth for every registered tool."""
